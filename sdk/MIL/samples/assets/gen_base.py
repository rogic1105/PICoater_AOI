"""gen_base.py — 生成四象限漸層格子底圖 256x256

四象限：
  左上 = 暖黃/橙色系
  右上 = 綠色系
  左下 = 紅色系
  右下 = 紫/藍紫色系

6x6 格子（每象限 3x3），小方塊圓角，方塊間留間隙。
"""
from PIL import Image, ImageDraw

S = 256
GRID = 6          # 整個 icon 幾格
GAP = 6           # 格間距 px（在 256px 下）
CORNER = 6        # 小方塊圓角

# 四象限各 3x3 的顏色漸層（左上→右下方向深淺）
# 格子座標 (row, col) 0-based；row 0=上, col 0=左
QUAD_COLORS = {
    # 左上 (row<3, col<3)：暖黃/橙
    (0, 0): (255, 230,  80),
    (0, 1): (255, 200,  60),
    (0, 2): (250, 170,  40),
    (1, 0): (255, 210,  90),
    (1, 1): (240, 180,  50),
    (1, 2): (230, 145,  30),
    (2, 0): (245, 190,  70),
    (2, 1): (225, 155,  40),
    (2, 2): (210, 125,  20),
    # 右上 (row<3, col>=3)：綠色系
    (0, 3): (160, 220, 100),
    (0, 4): (100, 200,  80),
    (0, 5): ( 60, 175,  60),
    (1, 3): (130, 210,  90),
    (1, 4): ( 80, 185,  70),
    (1, 5): ( 40, 155,  50),
    (2, 3): (100, 190,  75),
    (2, 4): ( 60, 165,  55),
    (2, 5): ( 30, 135,  40),
    # 左下 (row>=3, col<3)：紅色系
    (3, 0): (255, 100,  80),
    (3, 1): (230,  70,  60),
    (3, 2): (200,  45,  40),
    (4, 0): (240,  80,  65),
    (4, 1): (210,  55,  45),
    (4, 2): (180,  30,  30),
    (5, 0): (220,  60,  50),
    (5, 1): (190,  40,  35),
    (5, 2): (160,  20,  20),
    # 右下 (row>=3, col>=3)：紫/藍紫色系
    (3, 3): (180, 120, 220),
    (3, 4): (140,  90, 200),
    (3, 5): (100,  60, 180),
    (4, 3): (155, 100, 210),
    (4, 4): (115,  70, 185),
    (4, 5): ( 80,  45, 160),
    (5, 3): (130,  80, 195),
    (5, 4): ( 95,  55, 170),
    (5, 5): ( 65,  35, 145),
}

img = Image.new("RGBA", (S, S), (255, 255, 255, 255))
d = ImageDraw.Draw(img)

# 計算每格尺寸（留邊 + 間隙）
MARGIN = GAP  # 外邊距
total_gaps = GAP * (GRID - 1)
total_margins = MARGIN * 2
cell = (S - total_margins - total_gaps) // GRID  # 每格寬高

for r in range(GRID):
    for c in range(GRID):
        x0 = MARGIN + c * (cell + GAP)
        y0 = MARGIN + r * (cell + GAP)
        x1 = x0 + cell - 1
        y1 = y0 + cell - 1
        color = QUAD_COLORS[(r, c)] + (255,)
        d.rounded_rectangle([x0, y0, x1, y1], radius=CORNER, fill=color)

out = "MilGrabber_base.png"
img.save(out)
print(f"saved {out}  ({S}x{S})")
